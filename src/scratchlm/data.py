"""UTF-8 tokens and sliding next-token windows (chapter 2 concepts)."""

import torch
from torch.utils.data import Dataset


class ByteTokenizer:
    """A fixed vocabulary keeps the demo offline and handles unseen Unicode.

    IDs 0..255 encode UTF-8 bytes; 256 ends a sequence and 257 pads a batch.
    Unlike the book's GPT-2 BPE tokenizer, this uses one token per byte.
    """

    eos_id = 256
    pad_id = 257
    vocab_size = 258

    def encode(self, text: str, *, add_eos: bool = False) -> list[int]:
        ids = list(text.encode("utf-8"))
        return ids + [self.eos_id] if add_eos else ids

    def decode(self, ids: list[int]) -> str:
        if any(i < 0 or i >= self.vocab_size for i in ids):
            raise ValueError("Token ID outside the vocabulary")
        # Generated byte fragments need not form valid UTF-8; expose replacements.
        return bytes(i for i in ids if i < 256).decode("utf-8", errors="replace")


class TokenWindows(Dataset):
    """Predict x[t+1] from x[:t+1]; never pad a language-model window."""

    def __init__(self, tokens: list[int], context_length: int, stride: int | None = None):
        stride = context_length if stride is None else stride
        if context_length < 1 or stride < 1:
            raise ValueError("context_length and stride must be positive")
        if len(tokens) <= context_length:
            raise ValueError("Need at least context_length + 1 tokens")
        self.tokens = torch.tensor(tokens, dtype=torch.long)
        self.context_length = context_length
        self.starts = range(0, len(tokens) - context_length, stride)

    def __len__(self):
        return len(self.starts)

    def __getitem__(self, index):
        start = self.starts[index]
        end = start + self.context_length
        return self.tokens[start:end], self.tokens[start + 1:end + 1]


def split_tokens(tokens: list[int], train_fraction: float = 0.9):
    """Split the stream BEFORE windowing to avoid overlapping train/val windows."""
    if not 0 < train_fraction < 1:
        raise ValueError("train_fraction must lie strictly between zero and one")
    cut = int(len(tokens) * train_fraction)
    return tokens[:cut], tokens[cut:]
